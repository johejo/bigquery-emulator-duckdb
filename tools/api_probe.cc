// Probes the methods of the BigQuery v2 REST API, as third_party/bigquery/discovery.json lists
// them, against the emulator's HTTP server and prints a Markdown report of which ones it serves.
// Each request is sent to a fresh emulator holding the fixture the methods file's setup requests
// create. A method the file gives no requests for is probed with one the probe builds from the
// method's path. A probe checks only that a request succeeds, not that the response matches
// BigQuery's; a note in the file describes behavior a probe cannot observe.


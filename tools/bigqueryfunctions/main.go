// Command bigqueryfunctions regenerates tools/bigquery_functions.txt from the function list in the
// Markdown snapshot of BigQuery's documentation, which is the only list of BigQuery's functions
// Google publishes. Conditional expressions such as IF are documented on a page of their own, so
// they are read from there.
//
//	bigqueryfunctions OUTPUT functions-all.md conditional_expressions.md
package main

import (
	"fmt"
	"io"
	"os"
	"regexp"
	"slices"
	"strings"
)

const base = "https://docs.cloud.google.com/bigquery/docs/reference/standard-sql"

// row matches a row of a function table, which starts with a link to the function, such as
// | [`NAME` (JSON)](BASE/PAGE#ANCHOR), where the text after the name tells apart functions of the
// same name.
var row = regexp.MustCompile("(?m)^\\| *\\[`([A-Z][A-Z0-9_.]*)`[^\\]]*\\]\\(" + regexp.QuoteMeta(base) + "/([^)#]+#[^)]+)\\)")

// functions returns "NAME PAGE#ANCHOR" for every row of the function tables in the pages.
func functions(pages ...string) []string {
	var lines []string
	for _, page := range pages {
		for _, m := range row.FindAllStringSubmatch(page, -1) {
			lines = append(lines, m[1]+" "+m[2])
		}
	}
	slices.Sort(lines)
	return slices.Compact(lines)
}

func write(w io.Writer, lines []string) error {
	_, err := fmt.Fprintf(w, "# Generated by tools/bigqueryfunctions from the BigQuery documentation.\n"+
		"# Each line is a function name and its page and anchor under %s. A name BigQuery\n"+
		"# documents on several pages has a line for each.\n%s\n", base, strings.Join(lines, "\n"))
	return err
}

func run(out string, inputs []string) error {
	var pages []string
	for _, input := range inputs {
		b, err := os.ReadFile(input)
		if err != nil {
			return err
		}
		pages = append(pages, string(b))
	}
	lines := functions(pages...)
	if len(lines) == 0 {
		return fmt.Errorf("no function tables found; review the documentation's format")
	}
	f, err := os.Create(out)
	if err != nil {
		return err
	}
	if err := write(f, lines); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	fmt.Printf("wrote %d functions to %s\n", len(lines), out)
	return nil
}

func main() {
	if len(os.Args) < 3 {
		fmt.Fprintln(os.Stderr, "usage: bigqueryfunctions OUTPUT PAGE.md...")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/johejo/bigquery-emulator-duckdb/internal/functioncoverage"
	"github.com/johejo/bigquery-emulator-duckdb/internal/probereport"
)

const functionTypesGenerated = "<!-- Generated by tools/functioncoverage and tools/restprobe. Do not edit; run `just docs` to regenerate. -->\n"

// Group by the specification page, not by the emulator's registrations. Keep one catalog and
// one set of probe results while making the human-facing detail pages independently readable.
func functionTypeDomain(source string) string {
	domain := strings.TrimSuffix(filepath.Base(source), ".md")
	for _, suffix := range []string{"_functions", "-functions", "_expressions"} {
		domain = strings.TrimSuffix(domain, suffix)
	}
	return strings.ReplaceAll(domain, "_", "-")
}

func functionTypeAnchor(name string) string {
	return strings.ToLower(strings.ReplaceAll(name, ".", ""))
}

func functionTypeReports(known map[string]bool, catalog functioncoverage.Catalog, calls []typedCall) map[string][]byte {
	byName := map[string][]typedCall{}
	for _, call := range calls {
		byName[call.function.Name] = append(byName[call.function.Name], call)
	}
	domains := map[string]*bytes.Buffer{}
	links := map[string]string{}
	for _, f := range catalog.Functions {
		domain := functionTypeDomain(f.Source)
		path := "function-types/" + domain + ".md"
		links[f.Name] = path + "#" + functionTypeAnchor(f.Name)
		w := domains[domain]
		if w == nil {
			w = &bytes.Buffer{}
			domains[domain] = w
			words := strings.Split(domain, "-")
			for i, word := range words {
				if word != "" {
					words[i] = strings.ToUpper(word[:1]) + word[1:]
				}
			}
			fmt.Fprintf(w, "# BigQuery function support by type: %s\n\n%s\n[All functions and coverage notes](../function-types.md).\n\n## Functions\n\n", strings.Join(words, " "), functionTypesGenerated)
			for _, other := range catalog.Functions {
				if functionTypeDomain(other.Source) == domain {
					fmt.Fprintf(w, "- [%s](#%s)\n", other.Name, functionTypeAnchor(other.Name))
				}
			}
		}
		fmt.Fprintf(w, "\n## %s\n\nSource: [%s](../../%s).\n", f.Name, f.Name, f.Source)
		if f.Note != "" {
			fmt.Fprintf(w, "\n%s\n", f.Note)
		}
		fmt.Fprint(w, "\n| Input types | Return type | Status | Notes |\n| --- | --- | --- | --- |\n")
		for _, call := range byName[f.Name] {
			status := probereport.Status(map[probereport.Outcome]int{call.probe.Outcome: 1})
			fmt.Fprintf(w, "| `%s` | `%s` | %s | %s |\n", strings.Join(call.signature.Arguments, ", "), call.signature.Result, status, probereport.Escape(call.probe.Detail))
		}
	}
	var index bytes.Buffer
	fmt.Fprint(&index, functionTypesPreamble)
	fmt.Fprintf(&index, "\nType signatures are enumerated for **%d of %d functions**. The remaining **%d** are not enumerated; their function-level probes are listed in [functions.md](functions.md).\n", len(catalog.Functions), len(known), len(known)-len(catalog.Functions))
	fmt.Fprint(&index, "\n## Details by domain\n\n")
	var names []string
	for name := range domains {
		names = append(names, name)
	}
	slices.Sort(names)
	reports := map[string][]byte{}
	for _, domain := range names {
		path := "function-types/" + domain + ".md"
		fmt.Fprintf(&index, "- [%s](%s)\n", domain, path)
		reports[path] = domains[domain].Bytes()
	}
	fmt.Fprint(&index, "\n## Coverage\n\n| Function | Enumerated forms | Status |\n| --- | --- | --- |\n")
	for _, name := range probereport.SortedNames(known) {
		entries := byName[name]
		if len(entries) == 0 {
			fmt.Fprintf(&index, "| `%s` | 0 | Not enumerated |\n", name)
			continue
		}
		counts := map[probereport.Outcome]int{}
		for _, call := range entries {
			counts[call.probe.Outcome]++
		}
		status := probereport.Status(counts)
		// Incomplete type coverage must not become Supported just because the buildable calls run.
		if counts[probereport.Untested] > 0 && status != "Broken" {
			status = "Untested"
		}
		fmt.Fprintf(&index, "| [%s](%s) | %d | %s |\n", name, links[name], len(entries), status)
	}
	reports["function-types.md"] = index.Bytes()
	return reports
}

// The detail directory is owned by this generator. Check detects missing, changed and obsolete
// Markdown pages without writing anything; regeneration also removes obsolete detail pages.
func syncFunctionTypeReports(dir string, reports map[string][]byte, check bool) error {
	entries, err := os.ReadDir(filepath.Join(dir, "function-types"))
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	var obsolete []string
	for _, entry := range entries {
		name := "function-types/" + entry.Name()
		if !entry.IsDir() && strings.HasSuffix(name, ".md") {
			if _, ok := reports[name]; !ok {
				obsolete = append(obsolete, name)
			}
		}
	}
	var names []string
	for name := range reports {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if check {
			got, err := os.ReadFile(path)
			if err != nil {
				return fmt.Errorf("%s: %w; run just docs-function-types", path, err)
			}
			if !bytes.Equal(got, reports[name]) {
				return fmt.Errorf("%s is stale; run just docs-function-types", path)
			}
		} else {
			if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
				return err
			}
			if err := os.WriteFile(path+".tmp", reports[name], 0644); err != nil {
				return err
			}
			if err := os.Rename(path+".tmp", path); err != nil {
				return err
			}
		}
	}
	for _, name := range obsolete {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if check {
			return fmt.Errorf("%s is obsolete; run just docs-function-types", path)
		}
		if err := os.Remove(path); err != nil {
			return err
		}
	}
	return nil
}
